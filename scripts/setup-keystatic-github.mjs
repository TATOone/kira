#!/usr/bin/env node
/**
 * One-shot: create Keystatic GitHub App via Manifest flow,
 * write .env, print Cloudflare secret commands.
 */
import { createServer } from 'node:http';
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { execSync } from 'node:child_process';

const PORT = 8788;
const APP_NAME = 'kira-resurs-materinstva';
const KEYSTATIC_SECRET = randomBytes(32).toString('hex');
const REDIRECT = `http://127.0.0.1:${PORT}/callback`;

const manifest = {
  name: APP_NAME,
  url: 'https://resurs-materinstva.ru/keystatic',
  hook_attributes: {
    url: 'https://resurs-materinstva.ru/api/keystatic/github/webhook',
  },
  redirect_url: REDIRECT,
  callback_urls: [
    'https://resurs-materinstva.ru/api/keystatic/github/oauth/callback',
    'http://localhost:4321/api/keystatic/github/oauth/callback',
    'http://127.0.0.1:4321/api/keystatic/github/oauth/callback',
  ],
  request_oauth_on_install: true,
  public: false,
  default_permissions: {
    contents: 'write',
    metadata: 'read',
    pull_requests: 'read',
  },
  default_events: [],
};

const formHtml = `<!doctype html>
<html lang="ru">
<head><meta charset="utf-8"><title>Создать GitHub App для Keystatic</title></head>
<body style="font-family:system-ui;max-width:40rem;margin:3rem auto;padding:0 1rem">
  <h1>Создание GitHub App</h1>
  <p>Нажмите кнопку ниже (нужен вход в GitHub как <b>TATOone</b>). После создания приложения браузер вернётся сюда автоматически.</p>
  <form action="https://github.com/settings/apps/new" method="post">
    <input type="hidden" name="manifest" value='${JSON.stringify(manifest).replace(/'/g, '&#39;')}' />
    <button type="submit" style="font-size:1.1rem;padding:0.75rem 1.25rem;cursor:pointer">Создать GitHub App</button>
  </form>
</body>
</html>`;

function writeEnv(creds) {
  const env = `# Generated by scripts/setup-keystatic-github.mjs
PUBLIC_SITE_URL=https://resurs-materinstva.ru
PUBLIC_KEYSTATIC_STORAGE=github
PUBLIC_KEYSTATIC_GITHUB_REPO_OWNER=TATOone
PUBLIC_KEYSTATIC_GITHUB_REPO_NAME=kira
PUBLIC_KEYSTATIC_GITHUB_APP_SLUG=${creds.slug}
KEYSTATIC_GITHUB_CLIENT_ID=${creds.client_id}
KEYSTATIC_GITHUB_CLIENT_SECRET=${creds.client_secret}
KEYSTATIC_SECRET=${KEYSTATIC_SECRET}
`;
  writeFileSync('.env', env);
  writeFileSync('.keystatic-github-creds.json', JSON.stringify({ ...creds, KEYSTATIC_SECRET }, null, 2));
  console.log('\n✓ Записан .env и .keystatic-github-creds.json\n');
}

const server = createServer(async (req, res) => {
  const url = new URL(req.url || '/', `http://127.0.0.1:${PORT}`);

  if (url.pathname === '/') {
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
    res.end(formHtml);
    return;
  }

  if (url.pathname === '/callback') {
    const code = url.searchParams.get('code');
    if (!code) {
      res.writeHead(400, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end('Нет code в URL. Создайте приложение ещё раз.');
      return;
    }

    try {
      const response = await fetch(`https://api.github.com/app-manifests/${code}/conversions`, {
        method: 'POST',
        headers: {
          Accept: 'application/vnd.github+json',
          'User-Agent': 'kira-keystatic-setup',
        },
      });
      const data = await response.json();
      if (!response.ok) {
        throw new Error(JSON.stringify(data));
      }

      const creds = {
        id: data.id,
        slug: data.slug,
        client_id: data.client_id,
        client_secret: data.client_secret,
        html_url: data.html_url,
        install_url: `https://github.com/apps/${data.slug}/installations/new`,
      };
      writeEnv(creds);

      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      res.end(`<!doctype html><html lang="ru"><body style="font-family:system-ui;max-width:40rem;margin:3rem auto;padding:0 1rem">
        <h1>Готово</h1>
        <p>GitHub App <b>${creds.slug}</b> создан. Секреты сохранены локально.</p>
        <p><a href="${creds.install_url}" target="_blank" rel="noopener">Установить приложение на репозиторий TATOone/kira</a> (выберите Only select repositories → kira).</p>
        <p>Можно закрыть эту вкладку и вернуться в Cursor.</p>
      </body></html>`);

      console.log('App slug:', creds.slug);
      console.log('Client ID:', creds.client_id);
      console.log('Install:', creds.install_url);
      console.log('\nДальше: установите App на репозиторий (ссылка выше), затем скажите ассистенту продолжить.\n');
      setTimeout(() => process.exit(0), 500);
    } catch (error) {
      console.error(error);
      res.writeHead(500, { 'Content-Type': 'text/plain; charset=utf-8' });
      res.end(String(error));
    }
    return;
  }

  res.writeHead(404);
  res.end('Not found');
});

server.listen(PORT, '127.0.0.1', () => {
  const openUrl = `http://127.0.0.1:${PORT}/`;
  console.log(`Откройте в браузере (под аккаунтом TATOone):\n  ${openUrl}\n`);
  try {
    execSync(`open "${openUrl}"`, { stdio: 'ignore' });
  } catch {
    // ignore
  }
});
